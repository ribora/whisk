package generator

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"gitlab.com/gorib/whisk/internal/shared"
)

const GenFileSuffix = "_whisk_gen.go"

// Generate runs the whisk pipeline for one source file and writes the result,
// or nothing if no plugin contributed code.
func Generate(targetFile string, plugins []Plugin) error {
	pkgDir := filepath.Dir(targetFile)
	if pkgDir == "" {
		pkgDir = "."
	}

	genPath := GenFileName(targetFile)
	// Remove before Load: stale output may reference renamed fields and break
	// the type-check. Missing file is fine.
	if err := os.Remove(genPath); err != nil && !os.IsNotExist(err) {
		return fmt.Errorf("remove stale %s: %w", genPath, err)
	}

	formatted, warnings, err := loadAndRender(pkgDir, targetFile, plugins)
	if err != nil {
		return err
	}
	for _, w := range warnings {
		fmt.Fprintf(os.Stderr, "whisk: warning: %s\n", w)
	}
	if formatted == nil {
		return nil
	}

	if existing, err := os.ReadFile(genPath); err == nil && bytes.Equal(existing, formatted) {
		return nil
	}
	return os.WriteFile(genPath, formatted, 0o644)
}

// Render runs the plugins and returns the formatted file plus non-fatal
// warnings. Code is nil when no plugin contributed.
func Render(pkgName string, structs []shared.StructInfo, plugins []Plugin) ([]byte, []string, error) {
	var sections [][]byte
	var warnings []string
	importSet := map[string]struct{}{}
	for _, p := range plugins {
		sec, err := p.Generate(structs)
		if err != nil {
			return nil, nil, fmt.Errorf("plugin %s: %w", p.Name(), err)
		}
		warnings = append(warnings, sec.Warnings...)
		if len(sec.Code) == 0 {
			continue
		}
		sections = append(sections, sec.Code)
		for _, imp := range sec.Imports {
			importSet[imp] = struct{}{}
		}
	}
	if len(sections) == 0 {
		return nil, warnings, nil
	}
	out := renderFile(pkgName, sortedKeys(importSet), sections)
	formatted, err := format.Source(out)
	if err != nil {
		return nil, warnings, fmt.Errorf("format generated source: %w\n--- raw ---\n%s", err, out)
	}
	return formatted, warnings, nil
}

func loadAndRender(pkgDir, targetFile string, plugins []Plugin) ([]byte, []string, error) {
	pkgName, structs, err := shared.Load(pkgDir, targetFile)
	if err != nil {
		return nil, nil, err
	}
	if len(structs) == 0 {
		return nil, nil, nil
	}
	return Render(pkgName, structs, plugins)
}

func GenFileName(src string) string {
	base := strings.TrimSuffix(filepath.Base(src), ".go")
	return filepath.Join(filepath.Dir(src), base+GenFileSuffix)
}

func renderFile(pkgName string, imports []string, sections [][]byte) []byte {
	var sb bytes.Buffer
	fmt.Fprintf(&sb, "//go:build !%s\n\n", shared.BuildTag)
	sb.WriteString("// Code generated by whisk. DO NOT EDIT.\n\n")
	fmt.Fprintf(&sb, "package %s\n\n", pkgName)

	if len(imports) > 0 {
		sb.WriteString("import (\n")
		for _, imp := range imports {
			// "alias path" token → `alias "path"`; plain path → `"path"`.
			if alias, path, ok := splitAliasedImport(imp); ok {
				fmt.Fprintf(&sb, "\t%s %q\n", alias, path)
				continue
			}
			fmt.Fprintf(&sb, "\t%q\n", imp)
		}
		sb.WriteString(")\n\n")
	}

	for i, sec := range sections {
		if i > 0 {
			// Guarantee a blank line between sections; gofmt collapses extras.
			if !bytes.HasSuffix(sb.Bytes(), []byte("\n\n")) {
				sb.WriteByte('\n')
			}
		}
		sb.Write(sec)
	}
	return sb.Bytes()
}

func sortedKeys(m map[string]struct{}) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

// splitAliasedImport splits an "alias path" token; ok=false for a plain path
// (no space) or an alias with non-identifier characters.
func splitAliasedImport(token string) (alias, path string, ok bool) {
	sp := strings.IndexByte(token, ' ')
	if sp <= 0 || sp == len(token)-1 {
		return "", "", false
	}
	alias, path = token[:sp], token[sp+1:]
	for _, r := range alias {
		isLetter := (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || r == '_'
		isDigit := r >= '0' && r <= '9'
		if !isLetter && !isDigit {
			return "", "", false
		}
	}
	return alias, path, true
}
